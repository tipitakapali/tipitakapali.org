#!/usr/bin/env python3
"""
warm_dict_cache.py
==================

Two-phase helper for the tipitakapali.org dictionary:

  Phase 1 (words)
      Scan the full Roman-script Pāli text (server_api/db/books_xml.db)
      and build a frequency table of unique words, sorted by frequency ->
      scripts/dict_word_frequencies.tsv

  Phase 2 (warm)
      Take the top --percent (default 20%) most frequent unique words and
      issue the SAME requests the reader sends when a user clicks a word:

          GET {base}/api/dict/lookup?w=<word>&dict=dpd
          GET {base}/api/dict/lookup?w=<word>&dict=others

      (see context/DictionaryContext.jsx:performLookup — it fires these two
      lowercase requests in parallel for every click-to-lookup).

Notes
-----
* https://tipitakapali.org/api/dict/* does NOT exist (static site, 404).
  Browser lookups go straight to https://api.tipitakapali.org (see
  services/api.js:getApiBase), so that is the default --base-url.
* Edge caching only happens if Cloudflare is configured to cache
  /api/dict/* (default Cloudflare cache only stores known static file
  extensions; JSON is "DYNAMIC" unless a Cache Rule opts it in).
  The live progress + final summary show the `cf-cache-status` header:
      HIT            -> served from the Cloudflare edge
      MISS/DYNAMIC   -> served by origin (and NOT stored, when DYNAMIC)
  If everything is DYNAMIC/BYPASS, add a Cache Rule in the Cloudflare
  dashboard: api.tipitakapali.org/api/dict/*  ->  Eligible for cache,
  Edge TTL: respect origin Cache-Control.
* Progress is checkpointed to a JSONL file, so Ctrl-C and re-running
  resumes where it left off (use --no-resume to ignore the checkpoint).

Typical usage
-------------
    python3 scripts/warm_dict_cache.py --words-only        # just build the list
    python3 scripts/warm_dict_cache.py --dry-run           # preview selection
    python3 scripts/warm_dict_cache.py                     # warm top 20%
    python3 scripts/warm_dict_cache.py --percent 5
    python3 scripts/warm_dict_cache.py --dict dpd --top 5000 --workers 16
"""

import argparse
import html
import http.client
import json
import math
import re
import sqlite3
import sys
import threading
import time
from collections import Counter
from concurrent.futures import FIRST_COMPLETED, ThreadPoolExecutor, wait
from pathlib import Path
from urllib.parse import quote

SCRIPT_DIR = Path(__file__).resolve().parent
APP_DIR = SCRIPT_DIR.parent if (SCRIPT_DIR.parent / 'server_api').exists() else SCRIPT_DIR

DEFAULT_BASE_URL = 'https://api.tipitakapali.org'
DEFAULT_DICT_TYPES = 'dpd,others'
VALID_DICT_TYPES = {'all', 'dpd', 'others', 'rest', 'pts', 'abd', 'psd', 'sans', 'splitter'}

DEFAULT_WORDS_FILE = SCRIPT_DIR / 'dict_word_frequencies.tsv'
DEFAULT_CHECKPOINT = SCRIPT_DIR / 'dict_warm_checkpoint.jsonl'

TAG_RE = re.compile(r'<[^>]+>')
TOKEN_RE = re.compile(r'[^\W\d_]+', re.UNICODE)  # unicode letter runs (Pāli diacritics included)

UA = 'tipitakapali-dict-cache-warmer/1.0 (+https://tipitakapali.org)'


# ---------------------------------------------------------------------------
# Phase 1 — word frequency list
# ---------------------------------------------------------------------------

def resolve_xml_db(explicit: str | None) -> Path:
    candidates = []
    if explicit:
        candidates.append(Path(explicit))
    else:
        candidates += [
            APP_DIR / 'server_api' / 'db' / 'books_xml.db',
            Path.cwd() / 'server_api' / 'db' / 'books_xml.db',
        ]
    for cand in candidates:
        if cand.exists():
            return cand
    sys.exit(
        'error: Roman-script source not found. Pass --xml-db PATH '
        '(expected server_api/db/books_xml.db).'
    )


def build_word_frequencies(xml_db: Path, suffixes: set[str] | None) -> tuple[Counter, int]:
    """Tokenize every book's Roman XML and return (lowercase freq counter, total tokens)."""
    freq: Counter = Counter()
    total = 0
    con = sqlite3.connect(f'file:{xml_db}?mode=ro', uri=True)
    try:
        rows = con.execute('SELECT book_code, xml_content FROM books_xml')
        for code, xml in rows:
            if suffixes and code.rsplit('.', 1)[-1].lower() not in suffixes:
                continue
            text = html.unescape(TAG_RE.sub(' ', xml))
            tokens = TOKEN_RE.findall(text)
            total += len(tokens)
            freq.update(w.lower() for w in tokens)
    finally:
        con.close()
    return freq, total


def write_word_frequencies(path: Path, freq: Counter, total: int, source: Path):
    ordered = sorted(freq.items(), key=lambda kv: (-kv[1], kv[0]))
    with open(path, 'w', encoding='utf-8') as f:
        f.write('# Pāli word frequency list (Roman script) — generated by scripts/warm_dict_cache.py\n')
        f.write(f'# source: {source}\n')
        f.write(f'# total tokens: {total}\n')
        f.write(f'# unique words: {len(ordered)}\n')
        f.write('# columns: word<TAB>count (sorted by count desc, then alphabetically)\n')
        for word, count in ordered:
            f.write(f'{word}\t{count}\n')
    return ordered


def load_word_frequencies(path: Path) -> Counter:
    freq: Counter = Counter()
    with open(path, encoding='utf-8') as f:
        for line in f:
            if line.startswith('#'):
                continue
            parts = line.rstrip('\n').split('\t')
            if len(parts) == 2:
                freq[parts[0]] = int(parts[1])
    return freq


def top_frequencies(freq: Counter) -> list[tuple[str, int]]:
    return sorted(freq.items(), key=lambda kv: (-kv[1], kv[0]))


# ---------------------------------------------------------------------------
# HTTP machinery (stdlib only, one keep-alive connection per worker thread)
# ---------------------------------------------------------------------------

class ConnectionPool:
    def __init__(self, base_url: str, timeout: float):
        rest = base_url.split('://', 1)[1] if '://' in base_url else base_url
        host_port = rest.split('/', 1)[0]
        self.scheme = base_url.split('://', 1)[0] if '://' in base_url else 'https'
        self.host = host_port.rsplit(':', 1)[0]
        self.port = int(host_port.rsplit(':', 1)[1]) if ':' in host_port else (443 if self.scheme == 'https' else 80)
        self.timeout = timeout
        self.headers = {
            'User-Agent': UA,
            'Accept': '*/*',
            'Accept-Encoding': 'gzip, deflate, br',
            'Origin': 'https://tipitakapali.org',
            'Referer': 'https://tipitakapali.org/',
        }
        self._local = threading.local()

    def _conn(self):
        conn = getattr(self._local, 'conn', None)
        if conn is None:
            if self.scheme == 'https':
                conn = http.client.HTTPSConnection(self.host, self.port, timeout=self.timeout)
            else:
                conn = http.client.HTTPConnection(self.host, self.port, timeout=self.timeout)
            self._local.conn = conn
        return conn

    def close(self):
        conn = getattr(self._local, 'conn', None)
        if conn is not None:
            try:
                conn.close()
            except OSError:
                pass
            self._local.conn = None

    def get(self, path: str) -> tuple[int, dict]:
        conn = self._conn()
        conn.request('GET', path, headers=self.headers)
        resp = conn.getresponse()
        resp.read()  # drain body so the connection can be reused
        return resp.status, {k.lower(): v for k, v in resp.getheaders()}


class RateLimiter:
    def __init__(self, rate: float):
        self.interval = 1.0 / rate if rate > 0 else 0.0
        self.lock = threading.Lock()
        self.next_t = time.monotonic()

    def wait(self):
        if not self.interval:
            return
        with self.lock:
            now = time.monotonic()
            sleep_for = max(0.0, self.next_t - now)
            self.next_t = max(now, self.next_t) + self.interval
        if sleep_for:
            time.sleep(sleep_for)


class Stats:
    """Thread-safe counters + checkpoint writer."""

    def __init__(self, planned: int, checkpoint_path: Path, enabled: bool = True):
        self.planned = planned
        self.completed = 0
        self.requests = 0
        self.errors = 0
        self.ccs = Counter()          # cf-cache-status -> count
        self.done_by_type = Counter()  # dict type -> count
        self.lat_ms = {}              # ccs -> list of ms (kept for summary averages)
        self.error_samples = Counter()
        self.lock = threading.Lock()
        self.stop = threading.Event()
        self.start = time.monotonic()
        self.checkpoint_path = checkpoint_path
        self.checkpoint = open(checkpoint_path, 'a', encoding='utf-8') if enabled else None

    def record(self, word: str, dtype: str, status: int | None, ccs: str, age: str, ms: float, error: str | None):
        with self.lock:
            self.requests += 1
            self.completed += 1
            if error is not None:
                self.errors += 1
                self.error_samples[error[:80]] += 1
            else:
                self.done_by_type[dtype] += 1
                key = ccs or 'NONE'
                self.ccs[key] += 1
                self.lat_ms.setdefault(key, []).append(ms)
                if self.checkpoint is not None:
                    line = {
                        'w': word, 'd': dtype, 'status': status,
                        'ccs': key, 'age': age or '', 'ms': round(ms, 1),
                        't': int(time.time()),
                    }
                    self.checkpoint.write(json.dumps(line, ensure_ascii=False) + '\n')
                    self.checkpoint.flush()

    def snapshot(self):
        with self.lock:
            return self.completed, Counter(self.ccs), self.errors, self.requests

    def close(self):
        if self.checkpoint is not None:
            self.checkpoint.close()
            self.checkpoint = None


def do_request(pool: ConnectionPool, limiter: RateLimiter, stats: Stats,
               word: str, dtype: str, retries: int):
    """Perform one lookup, retrying transient failures. Records the outcome itself."""
    path = f'/api/dict/lookup?w={quote(word, safe="")}&dict={dtype}'
    attempts = 0
    while True:
        if stats.stop.is_set():
            return
        limiter.wait()
        if stats.stop.is_set():
            return
        t0 = time.monotonic()
        try:
            status, headers = pool.get(path)
            ms = (time.monotonic() - t0) * 1000
            if status == 429 or status >= 500:
                if attempts < retries:
                    attempts += 1
                    time.sleep(min(30.0, 0.5 * (2 ** attempts)))
                    continue
                stats.record(word, dtype, status, '', '', ms, error=f'HTTP {status}')
                return
            stats.record(word, dtype, status, headers.get('cf-cache-status', ''), headers.get('age', ''), ms, error=None)
            return
        except Exception as exc:  # noqa: BLE001 — network errors must not kill the pool
            ms = (time.monotonic() - t0) * 1000
            pool.close()
            if attempts < retries:
                attempts += 1
                time.sleep(min(10.0, 0.4 * attempts))
                continue
            stats.record(word, dtype, None, '', '', ms, error=repr(exc))
            return


# ---------------------------------------------------------------------------
# Checkpoint
# ---------------------------------------------------------------------------

def load_checkpoint(path: Path) -> set[tuple[str, str]]:
    done: set[tuple[str, str]] = set()
    if not path.exists():
        return done
    with open(path, encoding='utf-8') as f:
        for line in f:
            try:
                rec = json.loads(line)
                if isinstance(rec.get('status'), int) and 200 <= rec['status'] < 500 and rec.get('d'):
                    done.add((rec['w'], rec['d']))
            except (json.JSONDecodeError, KeyError, TypeError):
                continue
    return done


