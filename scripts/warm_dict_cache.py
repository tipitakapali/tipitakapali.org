def parse_args(argv=None):
    ap = argparse.ArgumentParser(
        description='Build a Pāli word frequency list and pre-warm the tipitakapali.org dictionary API cache.',
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    ap.add_argument('--words-only', action='store_true',
                    help='only build/refresh the word frequency list, no lookups')
    ap.add_argument('--dry-run', action='store_true',
                    help='show the selected words and request count, then exit')
    ap.add_argument('--percent', type=float, default=20.0,
                    help='percentage of unique words (top-N%% by frequency) to warm')
    ap.add_argument('--top', type=int, default=None,
                    help='absolute number of words to warm (overrides --percent)')
    ap.add_argument('--limit', type=int, default=None,
                    help='cap the number of words after selection (testing)')
    ap.add_argument('--min-count', type=int, default=1,
                    help='ignore words occurring fewer than N times')
    ap.add_argument('--book-suffix', default=None,
                    help='comma-separated book suffixes to include, e.g. "mul" or "mul,att" '
                         f'(available: att, mul, tik, nrf; default: all)')
    ap.add_argument('--dict', default=DEFAULT_DICT_TYPES,
                    help='comma-separated dict types, matching the click-to-lookup requests '
                         f'(valid: {", ".join(sorted(VALID_DICT_TYPES))})')
    ap.add_argument('--base-url', default=DEFAULT_BASE_URL,
                    help='dictionary API base URL')
    ap.add_argument('--workers', type=int, default=8, help='parallel request workers')
    ap.add_argument('--rate', type=float, default=25.0,
                    help='max requests per second across all workers (0 = unlimited)')
    ap.add_argument('--timeout', type=float, default=20.0, help='per-request timeout (seconds)')
    ap.add_argument('--retries', type=int, default=2, help='retries for transient errors (429/5xx/network)')
    ap.add_argument('--words-file', default=str(DEFAULT_WORDS_FILE),
                    help='word frequency table path (created if missing)')
    ap.add_argument('--rebuild-words', action='store_true',
                    help='rebuild the word frequency table even if it exists')
    ap.add_argument('--xml-db', default=None, help='path to books_xml.db (Roman-script source)')
    ap.add_argument('--checkpoint', default=str(DEFAULT_CHECKPOINT),
                    help='JSONL checkpoint of completed requests')
    ap.add_argument('--no-resume', action='store_true',
                    help='ignore an existing checkpoint')
    return ap.parse_args(argv)


def main(argv=None) -> int:
    args = parse_args(argv)

    # ---- Phase 1: word frequency table ------------------------------------
    words_path = Path(args.words_file)
    suffixes = None
    if args.book_suffix:
        suffixes = {s.strip().lower().lstrip('.') for s in args.book_suffix.split(',') if s.strip()}

    freq = None
    if words_path.exists() and not args.rebuild_words and not args.xml_db and not suffixes:
        freq = load_word_frequencies(words_path)
        if freq:
            print(f'[words] reusing {words_path} ({len(freq):,} unique words) — use --rebuild-words to refresh')
    if not freq:
        xml_db = resolve_xml_db(args.xml_db)
        t0 = time.monotonic()
        print(f'[words] scanning Roman-script corpus: {xml_db}')
        raw_freq, total = build_word_frequencies(xml_db, suffixes)
        ordered = write_word_frequencies(words_path, raw_freq, total, xml_db)
        print(f'[words] {total:,} tokens -> {len(ordered):,} unique words '
              f'in {time.monotonic() - t0:.1f}s -> {words_path}')
        freq = raw_freq

    ordered = top_frequencies(freq)
    print(f'[words] top 10: ' + ', '.join(f'{w}({c:,})' for w, c in ordered[:10]))

    if args.words_only:
        return 0

    # ---- Selection ---------------------------------------------------------
    eligible = [(w, c) for w, c in ordered if c >= args.min_count]
    if args.top:
        n_selected = min(args.top, len(eligible))
    else:
        n_selected = max(1, math.ceil(len(eligible) * args.percent / 100.0))
    selected = eligible[:n_selected]
    if args.limit:
        selected = selected[:args.limit]

    dict_types = [d.strip().lower() for d in args.dict.split(',') if d.strip()]
    bad = [d for d in dict_types if d not in VALID_DICT_TYPES]
    if bad:
        sys.exit(f'error: unknown dict type(s): {", ".join(bad)}')
    if not dict_types:
        sys.exit('error: --dict must contain at least one type')

    total_requests = len(selected) * len(dict_types)
    print(f'[select] {len(selected):,} words = '
          + (f'--top {args.top:,}' if args.top else f'top {args.percent:g}% of {len(eligible):,} unique words')
          + f'  x  {len(dict_types)} dict request(s) = {total_requests:,} lookups')

    if args.dry_run:
        print('[dry-run] first 15 words:')
        for word, count in selected[:15]:
            print(f'    {word:<30} {count:>8,}')
        print(f'[dry-run] base URL: {args.base_url}/api/dict/lookup')
        return 0

    # ---- Phase 2: warm -----------------------------------------------------
    checkpoint_path = Path(args.checkpoint)
    done_pairs = set() if args.no_resume else load_checkpoint(checkpoint_path)
    if done_pairs:
        print(f'[resume] checkpoint has {len(done_pairs):,} completed request(s): {checkpoint_path}')

    tasks: list[tuple[str, str]] = []
    skipped = 0
    for word, _count in selected:
        for dtype in dict_types:
            if (word, dtype) in done_pairs:
                skipped += 1
            else:
                tasks.append((word, dtype))

    if skipped:
        print(f'[resume] skipping {skipped:,} already-done request(s)')
    if not tasks:
        print('[warm] nothing to do — all selected requests are already checkpointed.')
        return 0

    if len(tasks) > 20000:
        est = len(tasks) / args.rate / 3600 if args.rate > 0 else 0
        print(f'[warm] {len(tasks):,} requests to make'
              + (f' (~{est:.1f}h at {args.rate:g} req/s)' if est else ''))

    pool = ConnectionPool(args.base_url, args.timeout)
    limiter = RateLimiter(args.rate)
    stats = Stats(planned=len(tasks), checkpoint_path=checkpoint_path)
    reporter_stop = threading.Event()
    reporter = threading.Thread(target=progress_loop, args=(stats, reporter_stop), daemon=True)
    reporter.start()

    interrupted = False
    with ThreadPoolExecutor(max_workers=args.workers) as executor:
        pending = set()
        it = iter(tasks)
        exhausted = False
        try:
            while pending or not exhausted:
                while not exhausted and len(pending) < args.workers * 8:
                    try:
                        word, dtype = next(it)
                    except StopIteration:
                        exhausted = True
                        break
                    pending.add(executor.submit(
                        do_request, pool, limiter, stats, word, dtype, args.retries))
                if not pending:
                    break
                done, pending = wait(pending, timeout=1.0, return_when=FIRST_COMPLETED)
                for fut in done:
                    fut.result()  # do_request never raises (except BaseException)
        except KeyboardInterrupt:
            interrupted = True
            stats.stop.set()
            sys.stderr.write('\n[interrupt] stopping workers, waiting for in-flight requests...\n')

    reporter_stop.set()
    reporter.join(timeout=5)
    stats.close()

    print_summary(stats, len(selected), dict_types, stats.error_samples)
    if interrupted:
        print(f'Interrupted — re-run to resume from {checkpoint_path}')
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        sys.exit(130)
