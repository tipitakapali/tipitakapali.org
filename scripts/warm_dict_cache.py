def fmt_duration(seconds: float) -> str:
    seconds = max(0, int(seconds))
    h, rem = divmod(seconds, 3600)
    m, s = divmod(rem, 60)
    return f'{h}h{m:02d}m' if h else (f'{m}m{s:02d}s' if m else f'{s}s')


def progress_loop(stats: Stats, reporter_stop: threading.Event):
    tty = sys.stderr.isatty()
    interval = 2.0 if tty else 30.0
    while not reporter_stop.wait(interval):
        completed, ccs, errors, _ = stats.snapshot()
        elapsed = time.monotonic() - stats.start
        rate = completed / elapsed if elapsed > 0 else 0
        hits = sum(v for k, v in ccs.items() if k in ('HIT', 'REVALIDATED', 'UPDATING'))
        remain = max(0, stats.planned - completed)
        eta = remain / rate if rate > 0 else 0
        line = (
            f'[progress] {completed:,}/{stats.planned:,} '
            f'({100 * completed / stats.planned:.1f}%)  '
            f'HIT {hits:,}  ERR {errors:,}  {rate:,.1f} req/s  ETA {fmt_duration(eta)}'
        )
        if tty:
            sys.stderr.write('\r' + line + '\x1b[K')
        else:
            sys.stderr.write(line + '\n')
        sys.stderr.flush()
    if tty:
        sys.stderr.write('\n')


def print_summary(stats: Stats, selected_words: int, dict_types: list[str], errors: Counter):
    completed, ccs, err_count, requests = stats.snapshot()
    elapsed = time.monotonic() - stats.start
    print('\n' + '=' * 72)
    print('Warm-up summary')
    print('=' * 72)
    print(f'Selected words     : {selected_words:,}  (dict types: {", ".join(dict_types)})')
    print(f'Requests this run  : {requests:,}   errors: {err_count:,}')
    print(f'Duration           : {fmt_duration(elapsed)}  ({requests / elapsed if elapsed else 0:,.1f} req/s avg)')
    if ccs:
        print('\ncf-cache-status distribution (successful requests):')
        total = sum(ccs.values())
        for key, count in ccs.most_common():
            lats = stats.lat_ms.get(key, [])
            avg = sum(lats) / len(lats) if lats else 0
            print(f'  {key:<12} {count:>10,}  ({100 * count / total:5.1f}%)  avg {avg:6.1f} ms')
        hit = sum(v for k, v in ccs.items() if k in ('HIT', 'REVALIDATED', 'UPDATING'))
        if total and hit == 0 and {'DYNAMIC', 'BYPASS'} & set(ccs):
            print('\nHint: no cache HITs — Cloudflare is currently NOT storing these responses.')
            print('      Add a Cache Rule: api.tipitakapali.org/api/dict/* -> Eligible for cache,')
            print('      then re-run to measure hits.')
    if errors:
        print('\nTop errors:')
        for msg, count in errors.most_common(5):
            print(f'  {count:>8,}  {msg}')
    print('=' * 72)


